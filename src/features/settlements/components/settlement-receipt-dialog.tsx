import { Printer } from "lucide-react";

import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { settlementMoney } from "@/features/settlements/policy";

export type SettlementReceipt = {
  number: string;
  farmerName: string;
  releasedAt: Date | string;
  amount: number;
  kind: "earnings" | "ipon";
  grossAmount?: number;
  serviceFee?: number;
  iponContribution?: number;
};

export function SettlementReceiptDialog({
  receipt,
  onOpenChange,
}: {
  receipt: SettlementReceipt | null;
  onOpenChange: (open: boolean) => void;
}) {
  return (
    <Dialog open={Boolean(receipt)} onOpenChange={onOpenChange}>
      <DialogContent className="max-h-[90dvh] overflow-y-auto rounded-3xl sm:max-w-xl">
        {receipt ? (
          <div data-settlement-receipt>
            <DialogHeader>
              <p className="text-xs font-semibold uppercase tracking-[0.18em] text-primary">
                AgriLink · PROCY
              </p>
              <DialogTitle className="text-2xl">
                {receipt.kind === "ipon" ? "IPON release receipt" : "Farmer payout receipt"}
              </DialogTitle>
              <DialogDescription>
                Official cash-release record generated by Accounting.
              </DialogDescription>
            </DialogHeader>
            <div className="mt-6 grid gap-3 rounded-2xl border border-border bg-muted/35 p-4 text-sm">
              <ReceiptRow label="Receipt number" value={receipt.number} />
              <ReceiptRow label="Farmer" value={receipt.farmerName} />
              <ReceiptRow
                label="Released"
                value={new Intl.DateTimeFormat("en-PH", {
                  dateStyle: "medium",
                  timeStyle: "short",
                  timeZone: "Asia/Manila",
                }).format(new Date(receipt.releasedAt))}
              />
              <ReceiptRow label="Payment method" value="Cash" />
            </div>
            {receipt.kind === "earnings" ? (
              <div className="mt-4 grid gap-2 rounded-2xl border border-border p-4 text-sm">
                <ReceiptRow
                  label="Gross sales share"
                  value={settlementMoney(receipt.grossAmount ?? 0)}
                />
                <ReceiptRow
                  label="PROCY service fee"
                  value={`− ${settlementMoney(receipt.serviceFee ?? 0)}`}
                />
                <ReceiptRow
                  label="Saved to IPON"
                  value={`− ${settlementMoney(receipt.iponContribution ?? 0)}`}
                />
              </div>
            ) : null}
            <div className="mt-4 rounded-2xl bg-primary p-5 text-primary-foreground">
              <p className="text-sm opacity-80">Cash released</p>
              <p className="mt-1 font-display text-3xl font-semibold">
                {settlementMoney(receipt.amount)}
              </p>
            </div>
            <DialogFooter className="mt-6 print:hidden">
              <Button className="rounded-full" onClick={() => window.print()}>
                <Printer className="size-4" />
                Print receipt
              </Button>
            </DialogFooter>
          </div>
        ) : null}
      </DialogContent>
    </Dialog>
  );
}

function ReceiptRow({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex items-start justify-between gap-4">
      <span className="text-muted-foreground">{label}</span>
      <span className="text-right font-medium">{value}</span>
    </div>
  );
}
